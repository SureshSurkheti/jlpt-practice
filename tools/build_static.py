def site_counts():
    """The figures the home page advertises, counted from the data files at
    build time. Typed into a template they would quietly go stale the first
    time a list grew; counted here they cannot."""
    counts = {"words": 0, "kanji": 0, "grammar": 0, "nepali": 0, "papers": 0}
    for level in LEVELS:
        for kind, field in (("words", "words"), ("kanji", "kanji"),
                            ("grammar", "patterns")):
            path = os.path.join(ROOT, "data", kind, level + ".json")
            if not os.path.exists(path):
                continue
            items = json.load(io.open(path, encoding="utf-8"))[field]
            counts[kind] += len(items)
            # Nepali is counted across words and grammar together, because
            # that is what somebody asking "is it in Nepali?" wants to know.
            if kind != "kanji":
                counts["nepali"] += sum(1 for x in items if x.get("ne"))
    idx = os.path.join(ROOT, "data", "exams", "index.json")
    if os.path.exists(idx):
        counts["papers"] = len(json.load(io.open(idx, encoding="utf-8"))["exams"])
    return counts


def coverage_counts():
    """How many words and patterns each level holds, and how many of them
    carry a Nepali gloss. Read from the data files at build time so the panel
    cannot drift from what the lists actually contain."""
    out = {}
    for level in LEVELS:
        row = {}
        for kind, field in (("words", "words"), ("kanji", "kanji"),
                            ("grammar", "patterns")):
            path = os.path.join(ROOT, "data", kind, level + ".json")
            if not os.path.exists(path):
                row[kind] = (0, 0)
                continue
            items = json.load(io.open(path, encoding="utf-8"))[field]
            row[kind] = (len(items), sum(1 for x in items if x.get("ne")))
        out[level] = row
    return out


def coverage_panel(table, en, here=None, prefix="study/", linked=True):
    """A five-row summary of what the lists hold and which languages the
    meanings are written in.

    It answers the two questions somebody arrives with - "is my level here?"
    and "is it in my language?" - without clicking through five tabs, and it
    is the only thing that links the ten list pages to each other. `here` is
    the "<level>-<kind>" page being written, so the panel does not link a
    page to itself."""
    counts = coverage_counts()
    head = "".join(
        '<th scope="col"%s>%s</th>' % (attr, label) for attr, label in (
            (' data-i18n="notice.colLevel"', esc(t(table, "notice.colLevel", en))),
            (' data-i18n="study.words"', esc(t(table, "study.words", en))),
            (' data-i18n="study.kanji"', esc(t(table, "study.kanji", en))),
            (' data-i18n="study.grammar"', esc(t(table, "study.grammar", en))),
            ("", "English"),
            (' lang="ne"', "\u0928\u0947\u092a\u093e\u0932\u0940"),
        ))

    rows = []
    for level in ["n5", "n4", "n3", "n2", "n1"]:
        c = counts[level]
        cells = []
        for kind in ("words", "kanji", "grammar"):
            total = c[kind][0]
            if not total:
                cells.append('<td><span class="coverage-no">&mdash;</span></td>')
                continue
            text = "{:,}".format(total)
            page = "%s-%s" % (level, kind)
            # On the hub the tabs underneath already switch level and list,
            # so linking these numbers gave the page two complete pickers for
            # the same fifteen combinations - one that navigates away, one
            # that filters in place, and nothing to say which. Here the table
            # is the summary and the tabs are the control. The fifteen list
            # pages keep the links: there the panel is the only thing joining
            # them to each other.
            cells.append('<td>%s</td>' % (
                '<span class="is-here">%s</span>' % text
                if (page == here or not linked)
                else '<a href="%s%s.html">%s</a>' % (prefix, page, text)))

        # English is on every entry; Nepali is complete for N5 and N4 and
        # covers the grammar patterns at every level. Say which, rather than
        # printing a tick that overstates it.
        ne_words, ne_gram = c["words"][1], c["grammar"][1]
        if ne_words and ne_gram:
            ne = '<span class="coverage-yes">&#10003;</span>'
        elif ne_gram:
            ne = ('<span class="coverage-yes">&#10003;</span> '
                  '<span class="coverage-part">%s</span>'
                  % esc(t(table, "study.grammar", en)))
        else:
            ne = '<span class="coverage-no">&mdash;</span>'

        rows.append(
            '<tr><th scope="row"><span class="lv-chip %s">%s</span></th>'
            '%s<td><span class="coverage-yes">&#10003;</span></td><td>%s</td></tr>'
            % (LEVEL_COLOR_CLASS[level], level.upper(), "".join(cells), ne))

    body = ('        <div class="coverage-wrap">\n'
            '          <table class="coverage-table">\n'
            '            <thead><tr>%s</tr></thead>\n'
            '            <tbody>%s</tbody>\n'
            '          </table>\n'
            '        </div>\n' % (head, "".join(rows)))
    title = esc(t(table, "notice.title", en))

    # On the hub the table folds away. It answers two questions - "is my level
    # here?" and "is it in my language?" - which a reader asks once and then
    # never again, and it was sitting between the page's own heading and the
    # controls that do the work, so every later visit scrolled past a screen
    # of reference material to reach the word list. Closed, the tabs and the
    # search box are the first thing under the heading.
    #
    # The fifteen list pages keep it open: there it is the only navigation
    # between them, so folding it would hide the way out of the page.
    if linked:
        return ('<section class="study-coverage">\n'
                '        <h2 data-i18n="notice.title">%s</h2>\n%s'
                '      </section>' % (title, body))

    return ('<details class="study-coverage is-static coverage-fold">\n'
            '        <summary><span data-i18n="notice.title">%s</span></summary>\n%s'
            '      </details>' % (title, body))


