def load_translations():
    src = io.open(os.path.join(ROOT, "assets/js/i18n-strings.js"),
                  encoding="utf-8").read()
    out = {}
    for lang, body in re.findall(r'I18N\.register\("([\w-]+)",\s*(\{.*?\n\}\);)',
                                 src, re.S):
        body = re.sub(r",(\s*\})", r"\1", body.rstrip(");").rstrip())
        out[lang] = json.loads(body)
    return out


def write_language_files(tr):
    """One small script per language instead of one big one for all twelve.

    assets/js/i18n-strings.js holds every language in a single file - 219 KB
    raw, 52 KB gzipped - and every page loaded all of it. Eleven twelfths of
    that was a language the visitor was not reading, and it was the largest
    asset on the site by a wide margin, larger than either stylesheet.

    Nothing needs it all any more: the language picker navigates to that
    language's own URL rather than repainting the page in place, so a page is
    only ever rendered in the one language it was built for. Each page now
    loads English (the fallback for any key a translation is missing) plus
    its own language, and nothing else.

    The big file stays where it is as the single source to edit; it is simply
    no longer served to anybody.
    """
    outdir = os.path.join(ROOT, "assets", "i18n")
    os.makedirs(outdir, exist_ok=True)
    for lang, table in tr.items():
        body = json.dumps(table, ensure_ascii=False, indent=1, sort_keys=True)
        io.open(os.path.join(outdir, lang + ".js"), "w", encoding="utf-8").write(
            "/* Generated by tools/build_static.py from "
            "assets/js/i18n-strings.js - do not edit. */\n"
            'I18N.register("%s", %s);\n' % (lang, body))
    return len(tr)


def t(table, key, fallback_table):
    if key in table:
        return table[key]
    return fallback_table.get(key, key)


def esc(text):
    return (str(text).replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


